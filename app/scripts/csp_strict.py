#!/usr/bin/env python3
"""Makes the iOS copy of the web app run under `script-src 'self'` (security audit LOW-02).

app/www/index.html stays byte-identical to the Android app's page. This step, run in CI before
`cap sync`, rewrites the copy that goes into the iOS build:

  1. the page's one inline <script> becomes www/aeolus-app.js (same code, same order);
  2. every inline handler in the markup (onclick="…", oninput="…") is removed and compiled into
     www/aeolus-handlers.js as a real function, bound to its element with addEventListener
     (`this` = the element, `event` = the event, `return false` = preventDefault, like an inline
     handler);
  3. handlers the page writes into innerHTML at run time can't run under the strict policy; the
     page builds only four of them (selectFiat('X'), changeTxPage(±1), expandTx(this),
     copyTxidFromRow(event)), so a click listener dispatches exactly those shapes to exactly
     those functions, with no eval, emulating bubbling (stopPropagation is honoured);
  4. the CSP's script-src drops 'unsafe-inline' (style-src keeps it: styles can't run code).

Fails loudly if the page no longer has the shape this expects (a second inline script, a new
run-time handler, single-quoted handlers, ...), so a new page can't silently break the iOS app.

    csp_strict.py <www dir>
"""
import html
import json
import re
import sys

DYNAMIC = ["selectFiat", "changeTxPage", "copyTxidFromRow", "expandTx"]
EVENTS = ["click", "input", "change", "keyup", "keydown", "submit", "focus", "blur", "load", "error"]

INLINE_SCRIPT = re.compile(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", re.S)
TAG = re.compile(r"<[a-zA-Z][^>]*>")
HANDLER = re.compile(r"\son([a-z]+)\s*=\s*\"([^\"]*)\"")
CSP = re.compile(r'(<meta[^>]+Content-Security-Policy"\s+content=")([^"]+)(")')


def fail(msg):
    sys.exit("csp_strict: " + msg)


def main():
    if len(sys.argv) != 2:
        fail("usage: csp_strict.py <www dir>")
    www = sys.argv[1].rstrip("/")
    page = open(www + "/index.html", encoding="utf-8").read()

    scripts = list(INLINE_SCRIPT.finditer(page))
    if len(scripts) != 1:
        fail("expected exactly one inline <script>, found %d" % len(scripts))
    app_js = scripts[0].group(1)

    # Run-time handlers in the script: only the known shapes.
    found = re.findall(r"on(" + "|".join(EVENTS) + r")\s*=\s*\\?[\"']([A-Za-z_$][\w$]*)", app_js)
    unknown = sorted({f"on{e}={fn}" for e, fn in found if e != "click" or fn not in DYNAMIC})
    if unknown:
        fail("new run-time handler(s) in the page script, add them to DYNAMIC if safe: " + ", ".join(unknown))
    for fn in DYNAMIC:
        if not re.search(r"\bfunction\s+" + re.escape(fn) + r"\s*\(", app_js):
            fail(fn + " is no longer a global function declaration")

    head, tail = page[:scripts[0].start()], page[scripts[0].end():]
    for part in (head, tail):
        if re.search(r"\son[a-z]+\s*=\s*'", part):
            fail("single-quoted inline handler: not supported")

    handlers = []   # (id, code)

    def rewrite_tag(m):
        tag = m.group(0)

        def one(h):
            ev, code = h.group(1), html.unescape(h.group(2))
            if ev not in EVENTS:
                fail("unexpected handler on" + ev)
            hid = str(len(handlers) + 1)
            handlers.append((hid, code))
            return f' data-zh-{ev}="{hid}"'
        return HANDLER.sub(one, tag)

    head = TAG.sub(rewrite_tag, head)
    tail = TAG.sub(rewrite_tag, tail)
    for part in (head, tail):
        left = re.findall(r"<[^>]*\son[a-z]+\s*=", part)
        if left:
            fail("inline handler left after rewrite: " + left[0][:80])

    m = CSP.search(head)
    if not m:
        fail("no CSP meta tag")
    csp = m.group(2)
    new_csp = re.sub(r"(script-src[^;]*?)\s+'unsafe-inline'", r"\1", csp)
    if "'unsafe-inline'" in re.search(r"script-src[^;]*", new_csp).group(0):
        fail("could not remove 'unsafe-inline' from script-src")
    head = head[:m.start(2)] + new_csp + head[m.end(2):]

    out = (head + '<script src="aeolus-app.js"></script>\n<script src="aeolus-handlers.js"></script>' + tail)
    open(www + "/index.html", "w", encoding="utf-8").write(out)
    open(www + "/aeolus-app.js", "w", encoding="utf-8").write(app_js)

    js = [
        "// Generated by app/scripts/csp_strict.py from index.html: the page's inline handlers as code,",
        "// so the iOS build runs under script-src 'self'. Do not edit.",
        "(function () {",
        "  var H = {",
    ]
    for hid, code in handlers:
        js.append("    %s: function (event) { %s\n    }," % (json.dumps(hid), code))
    js += [
        "  };",
        "  var EV = %s;" % json.dumps(EVENTS),
        "  function bind(el) {",
        "    EV.forEach(function (ev) {",
        "      var id = el.getAttribute('data-zh-' + ev);",
        "      if (!id || !H[id]) return;",
        "      el.addEventListener(ev, function (e) {",
        "        if (H[id].call(this, e) === false) e.preventDefault();",
        "      });",
        "    });",
        "  }",
        "  var sel = EV.map(function (ev) { return '[data-zh-' + ev + ']'; }).join(',');",
        "  Array.prototype.forEach.call(document.querySelectorAll(sel), bind);",
        "",
        "  // Run-time markup (innerHTML) handlers: only these functions, only literal arguments.",
        "  var DYN = %s;" % json.dumps({fn: 1 for fn in DYNAMIC}),
        "  function arg(a, el, e) {",
        "    a = a.trim();",
        "    if (a === '') return [];",
        "    if (a === 'this') return [el];",
        "    if (a === 'event') return [e];",
        "    if (/^-?\\d+(\\.\\d+)?$/.test(a)) return [Number(a)];",
        "    if (/^'[^'\\\\]*'$/.test(a)) return [a.slice(1, -1)];",
        "    return null;",
        "  }",
        "  document.addEventListener('click', function (e) {",
        "    for (var el = e.target; el && el !== document; el = el.parentNode) {",
        "      if (el.nodeType !== 1 || !el.hasAttribute('onclick')) continue;",
        "      var m = /^\\s*([A-Za-z_$][\\w$]*)\\((.*)\\)\\s*;?\\s*$/.exec(el.getAttribute('onclick'));",
        "      if (m && DYN[m[1]] && typeof window[m[1]] === 'function') {",
        "        var a = arg(m[2], el, e);",
        "        if (a) window[m[1]].apply(el, a);",
        "      }",
        "      if (e.cancelBubble) break;",
        "    }",
        "  });",
        "})();",
        "",
    ]
    open(www + "/aeolus-handlers.js", "w", encoding="utf-8").write("\n".join(js))
    print("csp_strict: %d handlers compiled, %d run-time shapes allowed, CSP: %s"
          % (len(handlers), len(DYNAMIC), re.search(r"script-src[^;]*", new_csp).group(0)))


if __name__ == "__main__":
    main()
